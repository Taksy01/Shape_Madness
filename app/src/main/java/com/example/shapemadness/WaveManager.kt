    var currentWaveIndex = 0 // Index de la vague en cours de traitement
    var isSpawningWave = false // Indique si des monstres sont en train de sortir
    var pendingMiniEnemies = 0 // Compteur pour les petits ennemis qui apparaissent après la mort d'un boss
    var isGameRunning = false // État global du moteur de vagues

    private val handler = Handler(Looper.getMainLooper()) // Gestionnaire pour les délais entre les apparitions
    private var remainingEnemiesToSpawn = mutableListOf<WaveEnemy>() // Liste temporaire des monstres restant à envoyer
    private var isBetweenWaves = false // Indique si le joueur est en phase de repos
    private var hasStartedFirstWave = false // Sécurité pour le tout premier lancement

    private var timeWhenTimerStarted = 0L // Heure exacte du début du chrono actuel
    private var remainingTimerDelay = 0L // Temps restant avant la prochaine apparition lors d'une pause
    private var savedAction: Runnable? = null // Mémorise l'action à reprendre après une pause

    // Force le passage à une vague spécifique pour le mode débug ou les récompenses
    fun forceWave(vague: Int) {
        this.currentWaveIndex = vague
    }

    // Lance un chronomètre précis qui peut être mis en pause et repris au millième de seconde
    private fun startExactTimer(delay: Long, action: () -> Unit) {
        savedAction = Runnable {
            savedAction = null // Efface l'action car elle est en train d'être exécutée
            if (isGameRunning) action()
        }
        remainingTimerDelay = delay
        timeWhenTimerStarted = System.currentTimeMillis() // Note le moment précis du départ
        handler.postDelayed(savedAction!!, delay)
    }

    // Prépare et lance l'apparition de la vague actuelle
    fun startWave() {
        if (isSpawningWave) return // Empêche de lancer deux vagues en même temps
        if (currentWaveIndex >= waves.size) return // Arrête le jeu si toutes les vagues sont terminées

        hasStartedFirstWave = true
        isSpawningWave = true
        isBetweenWaves = false
        onWaveStarted(currentWaveIndex + 1) // Informe l'interface que le combat reprend
        remainingEnemiesToSpawn = waves[currentWaveIndex].toMutableList() // Copie la liste des monstres à envoyer

        startExactTimer(2000L) { // Attend deux secondes avant de faire sortir le premier monstre
            spawnNextInWave()
        }
    }

    // Gère l'envoi successif de chaque monstre de la liste
    private fun spawnNextInWave() {
        if (remainingEnemiesToSpawn.isEmpty()) {
            isSpawningWave = false
            return
        }

        val nextEnemy = remainingEnemiesToSpawn.removeAt(0) // Retire le monstre de la liste d'attente
        onSpawnEnemyRequested(nextEnemy.type) // Demande la création visuelle du monstre

        if (remainingEnemiesToSpawn.isEmpty()) {
            isSpawningWave = false // Arrête le cycle si c'était le dernier de la vague
        } else {
            startExactTimer(nextEnemy.delayAfter) { // Attend le délai spécifique avant le prochain monstre
                spawnNextInWave()
            }
        }
    }

    // Vérifie si l'écran est vide pour passer à la vague suivante
    fun checkWaveCleared(activeEnemiesCount: Int) {
        if (!isSpawningWave && activeEnemiesCount == 0 && pendingMiniEnemies == 0) {
            isBetweenWaves = true
            val waveJustCleared = currentWaveIndex + 1 // Sauvegarde le numéro de la vague finie
            currentWaveIndex++

            onWaveCleared(waveJustCleared) // Informe le jeu pour distribuer les bonus

            if (waveJustCleared != 10 && waveJustCleared != 20) { // Ne relance pas auto si un choix de classe est attendu
                startExactTimer(3000L) { // Trois secondes de repos avant la suite
                    startWave()
                }
            }
        }
    }

    // Arrête tous les chronomètres et calcule le temps restant pour la reprise
    fun stop() {
        isGameRunning = false
        handler.removeCallbacksAndMessages(null) // Coupe net tous les délais en cours

        if (savedAction != null) {
            val elapsedTime = System.currentTimeMillis() - timeWhenTimerStarted // Calcule le temps déjà écoulé
            remainingTimerDelay -= elapsedTime // Déduit ce temps du délai total
            if (remainingTimerDelay < 0) remainingTimerDelay = 0
        }
    }

    // Relance le moteur de vagues exactement là où il s'était arrêté
    fun resume() {
        isGameRunning = true

        if (!hasStartedFirstWave) {
            startWave() // Démarre la toute première vague du jeu
        } else if (savedAction != null) {
            timeWhenTimerStarted = System.currentTimeMillis() // Repart sur un nouveau chrono propre
            handler.postDelayed(savedAction!!, remainingTimerDelay) // Utilise le temps restant calculé au stop
        }
    }
